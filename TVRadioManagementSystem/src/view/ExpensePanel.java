private void loadTable() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    List<Object[]> list = expenseDao.getAllExpensesWithProgramName();

    for (Object[] row : list) {
        model.addRow(row);
    }
}


    
