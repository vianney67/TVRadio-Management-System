    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
                                      
    try {
        // Get fields
        String category = categoryCombo.getSelectedItem().toString();
        String description = descriptionArea.getText();
        double amount = Double.parseDouble(amountTxt.getText());

        // Validate: amount must be positive
        if (amount <= 0) {
            JOptionPane.showMessageDialog(this, "Amount must be a positive number!");
            amountTxt.requestFocus();
            return;
        }

        // Get selected date from dateChooser
        java.util.Date selectedUtilDate = dateChooser.getDate();
        if (selectedUtilDate == null) {
            JOptionPane.showMessageDialog(this, "Select a date!");
            return;
        }

        // Validate: date should not be in the future
        java.util.Date today = new java.util.Date();
        if (selectedUtilDate.after(today)) {
            JOptionPane.showMessageDialog(this, "Expense date cannot be in the future!");
            return;
        }

        // Convert to java.sql.Date for DB
        java.sql.Date selectedDate = new java.sql.Date(selectedUtilDate.getTime());

        // Get program ID
        int selectedIndex = programCombo.getSelectedIndex();
        int programId = programList.get(selectedIndex).getProgramId();

        // Create Expense object
        Expense expense = new Expense(category, description, amount, selectedDate, programId);

        // Insert into DB
        if (expenseDao.insertExpense(expense)) {
            JOptionPane.showMessageDialog(this, "Expense Added Successfully!");
            loadTable();
            clearFields();
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter a valid numeric amount!");
        amountTxt.requestFocus();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error Adding Expense");
        e.printStackTrace();
    }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
                                            
   if (selectedExpenseId == -1) {
        JOptionPane.showMessageDialog(this, "Select an expense first");
        return;
    }

    try {
        String category = categoryCombo.getSelectedItem().toString();
        String description = descriptionArea.getText();
        double amount = Double.parseDouble(amountTxt.getText());

        // Validate: amount must be positive
        if (amount <= 0) {
            JOptionPane.showMessageDialog(this, "Amount must be a positive number!");
            amountTxt.requestFocus();
            return;
        }

        // Get selected date
        java.util.Date selectedUtilDate = dateChooser.getDate();
        if (selectedUtilDate == null) {
            JOptionPane.showMessageDialog(this, "Select a date!");
            return;
        }

        // Validate future date
        java.util.Date today = new java.util.Date();
        if (selectedUtilDate.after(today)) {
            JOptionPane.showMessageDialog(this, "Expense date cannot be in the future!");
            return;
        }

        // Convert to java.sql.Date for DB
        java.sql.Date selectedDate = new java.sql.Date(selectedUtilDate.getTime());

        // Get program ID
        int selectedIndex = programCombo.getSelectedIndex();
        int programId = programList.get(selectedIndex).getProgramId();

        // Create Expense object
        Expense expense = new Expense(selectedExpenseId, category, description, amount, selectedDate, programId);

        // Update DB
        if (expenseDao.updateExpense(expense)) {
            JOptionPane.showMessageDialog(this, "Expense Updated Successfully!");
            loadTable();
            clearFields();
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter a valid numeric amount!");
        amountTxt.requestFocus();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Update Failed");
        e.printStackTrace();
    }
    }//GEN-LAST:event_updateBtnActionPerformed

