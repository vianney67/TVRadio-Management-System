    private void loadChannelCombo() {
        channelCombo.removeAllItems();
        List<Channel> channels = channelDAO.getAllChannels();
        for (Channel ch : channels) {
            channelCombo.addItem(ch.getName());
        }
    }

    private void loadProgramCombo() {
        programCombo.removeAllItems();
        int selectedIndex = channelCombo.getSelectedIndex();
        if (selectedIndex >= 0) {
            Channel selectedChannel = channelDAO.getAllChannels().get(selectedIndex);
            List<Program> programs = programDAO.getProgramsByChannel(selectedChannel.getId());
            for (Program p : programs) {
                programCombo.addItem(p.getProgramName());
            }
        }
    }
    private void refreshAllCombos() {
    channelCombo.removeAllItems();
    programCombo.removeAllItems();
    employeeNameCombo.removeAllItems();
    roleCombo.removeAllItems();

    loadChannelCombo();
    loadEmployeeCombo();
    loadProgramCombo();

    roleCombo.addItem("Anchor");
    roleCombo.addItem("Camera Operator");
    roleCombo.addItem("Sound Engineer");
    roleCombo.addItem("Host");
    roleCombo.addItem("Producer");
    roleCombo.addItem("Director");
    roleCombo.addItem("Editor");
    roleCombo.addItem("Scriptwriter");
    roleCombo.addItem("Lighting Technician");
    roleCombo.addItem("Floor Manager");
}


    private void loadEmployeeCombo() {
        employeeNameCombo.removeAllItems();
        List<Employee> employees = employeeDAO.getAllEmployees();
        for (Employee e : employees) {
            employeeNameCombo.addItem(e.getFullName()); // Assuming getFullName() exists
        }
    }

    private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing rows

        List<ProgramAssignment> list = assignmentDAO.getAllAssignments();
        for (ProgramAssignment pa : list) {
            Channel ch = channelDAO.getChannelById(pa.getChannelId());
            Program p = programDAO.getProgramById(pa.getProgramId());
            Employee emp = employeeDAO.getEmployeeById(pa.getEmployeeId());

            model.addRow(new Object[]{
                    pa.getAssignmentId(),
                    ch != null ? ch.getName() : "",
                    p != null ? p.getProgramName() : "",
                    emp != null ? emp.getFullName() : "",
                    pa.getAssignedRole()
            });
        }
    }

   private void clearFields() {
    refreshAllCombos();   // ✅ reloads everything from DB
}


