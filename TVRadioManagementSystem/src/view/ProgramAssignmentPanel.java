    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        try {
            int channelId = channelDAO.getAllChannels().get(channelCombo.getSelectedIndex()).getId();
            int programId = programDAO.getProgramsByChannel(channelId).get(programCombo.getSelectedIndex()).getProgramId();
            int employeeId = employeeDAO.getAllEmployees().get(employeeNameCombo.getSelectedIndex()).getEmployeeId();
            String role = (String) roleCombo.getSelectedItem();

            ProgramAssignment pa = new ProgramAssignment(channelId, programId, employeeId, role);
            if (assignmentDAO.insertAssignment(pa)) {
                JOptionPane.showMessageDialog(this, "Assignment added successfully");
                loadTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add assignment");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Select valid entries");
        }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        try {
            int selectedRow = jTable1.getSelectedRow();
            if (selectedRow < 0) {
                JOptionPane.showMessageDialog(this, "Select a row to update");
                return;
            }

            int assignmentId = (int) jTable1.getValueAt(selectedRow, 0);
            int channelId = channelDAO.getAllChannels().get(channelCombo.getSelectedIndex()).getId();
            int programId = programDAO.getProgramsByChannel(channelId).get(programCombo.getSelectedIndex()).getProgramId();
            int employeeId = employeeDAO.getAllEmployees().get(employeeNameCombo.getSelectedIndex()).getEmployeeId();
            String role = (String) roleCombo.getSelectedItem();

            ProgramAssignment pa = new ProgramAssignment(assignmentId, channelId, programId, employeeId, role);
            if (assignmentDAO.updateAssignment(pa)) {
                JOptionPane.showMessageDialog(this, "Assignment updated successfully");
                loadTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update assignment");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Select valid entries");
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        try {
            int selectedRow = jTable1.getSelectedRow();
            if (selectedRow < 0) {
                JOptionPane.showMessageDialog(this, "Select a row to delete");
                return;
            }

            int assignmentId = (int) jTable1.getValueAt(selectedRow, 0);
            if (assignmentDAO.deleteAssignment(assignmentId)) {
                JOptionPane.showMessageDialog(this, "Assignment deleted successfully");
                loadTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete assignment");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error deleting assignment");
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

