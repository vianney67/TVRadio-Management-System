    // Validate all input fields before Add or Update
private boolean validateFields() {
    String name = programNameTxt.getText().trim();
    String type = programTypeTxt.getText().trim();
    String desc = descriptionArea.getText().trim();
    Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
    String status = (String) statusCombo.getSelectedItem();

    // Program Name
    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Program name cannot be empty!");
        programNameTxt.requestFocus();
        return false;
    }
    if (name.length() > 50) {
        JOptionPane.showMessageDialog(this, "Program name is too long! Max 50 characters.");
        programNameTxt.requestFocus();
        return false;
    }

    // Program Type
    if (type.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Program type cannot be empty!");
        programTypeTxt.requestFocus();
        return false;
    }
    if (type.length() > 30) {
        JOptionPane.showMessageDialog(this, "Program type is too long! Max 30 characters.");
        programTypeTxt.requestFocus();
        return false;
    }

    // Description (optional but limit length)
    if (desc.length() > 200) {
        JOptionPane.showMessageDialog(this, "Description is too long! Max 200 characters.");
        descriptionArea.requestFocus();
        return false;
    }

    // Channel selection
    if (selectedChannel == null) {
        JOptionPane.showMessageDialog(this, "Please select a channel!");
        channelCombo.requestFocus();
        return false;
    }

    // Status validation
   if (status == null || (!status.equals("Running") && !status.equals("Stopped"))) {
    JOptionPane.showMessageDialog(this, "Please select a valid status!");
    statusCombo.requestFocus();
    return false;
    }

    return true; // All validations passed
}

    
    // Helper Method: Load Channels into JComboBox
    private void loadChannels() {
        channelCombo.removeAllItems();
        List<Channel> channels = channelDAO.getAllChannels();
        for (Channel c : channels) {
            channelCombo.addItem(c);  // Channel should have toString() return name
        }
    }

    // Helper Method: Load Programs into JTable
    private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear existing rows

        List<Program> programs = programDAO.getAllPrograms();
        for (Program p : programs) {
            String channelName = channelDAO.getChannelById(p.getChannelId()).getName();
            model.addRow(new Object[]{
                    p.getProgramId(),
                    p.getProgramName(),
                    channelName,
                    p.getDescription(),
                    p.getProgramType(),
                    p.getStatus()
            });
        }
    }

    // Helper Method: Clear Input Fields
    private void clearFields() {
        programNameTxt.setText("");
        descriptionArea.setText("");
        programTypeTxt.setText("");
        if(statusCombo.getItemCount() > 0) statusCombo.setSelectedIndex(0);
        if(channelCombo.getItemCount() > 0) channelCombo.setSelectedIndex(0);
    }

