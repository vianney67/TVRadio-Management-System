    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed

        try {
        if (!validateFields()) return; // Validate first

        String name = programNameTxt.getText().trim();
        String desc = descriptionArea.getText().trim();
        String type = programTypeTxt.getText().trim();
        String status = (String) statusCombo.getSelectedItem();
        Channel selectedChannel = (Channel) channelCombo.getSelectedItem();

        Program program = new Program(name, selectedChannel.getId(), desc, type, status);

        if (programDAO.insertProgram(program)) {
            JOptionPane.showMessageDialog(this, "Program added successfully!");
            loadTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Error adding program!");
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed

       try {
            int selectedRow = jTable1.getSelectedRow();
            if(selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Select a program to update!");
                return;
            }

            int programId = (int) jTable1.getValueAt(selectedRow, 0);
            String name = programNameTxt.getText();
            String desc = descriptionArea.getText();
            String type = programTypeTxt.getText();
            String status = (String) statusCombo.getSelectedItem();
            Channel selectedChannel = (Channel) channelCombo.getSelectedItem();

            Program program = new Program(programId, name, selectedChannel.getId(), desc, type, status);
            if(programDAO.updateProgram(program)) {
                JOptionPane.showMessageDialog(this, "Program updated successfully!");
                loadTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Error updating program!");
            }
        } catch(Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
try {
            int selectedRow = jTable1.getSelectedRow();
            if(selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Select a program to delete!");
                return;
            }

            int programId = (int) jTable1.getValueAt(selectedRow, 0);
            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure to delete?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if(confirm == JOptionPane.YES_OPTION) {
                if(programDAO.deleteProgram(programId)) {
                    JOptionPane.showMessageDialog(this, "Program deleted successfully!");
                    loadTable();
                    clearFields();
                } else {
                    JOptionPane.showMessageDialog(this, "Error deleting program!");
                }
            }
        } catch(Exception e) {
            e.printStackTrace();
        }
      
    }//GEN-LAST:event_deleteBtnActionPerformed

