    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed

        try {
            String company = companyNameTxt.getText();
            Channel ch = (Channel) channelNameCombo.getSelectedItem();
            Program pr = (Program) programCombo.getSelectedItem();
            double cost = Double.parseDouble(costPaidTxt.getText());
            java.util.Date adDate = adDateChooser.getDate();
            java.util.Date durationDate = (java.util.Date) adDurationSpinner.getValue();
            String status = (String) paymentStatusCombo.getSelectedItem();

            if (ch == null || pr == null || adDate == null) {
                JOptionPane.showMessageDialog(this, "Please select channel, program, and date.");
                return;
            }

            java.sql.Time sqlDuration = new java.sql.Time(durationDate.getTime());

            Advertisement ad = new Advertisement(
                company,
                ch.getId(),
                pr.getProgramId(),
                cost,
                sqlDuration,
                new Date(adDate.getTime()),
                status
            );

            boolean success = adDao.addAdvertisement(ad);
            if (success) {
                JOptionPane.showMessageDialog(this, "Advertisement added successfully.");
                clearFields();
                loadAdvertisementTable();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: Invalid input.");
            e.printStackTrace();
        }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Select a row to update.");
            return;
        }

        try {
            int adId = (int) jTable1.getValueAt(selectedRow, 0);
            String company = companyNameTxt.getText();
            Channel ch = (Channel) channelNameCombo.getSelectedItem();
            Program pr = (Program) programCombo.getSelectedItem();
            double cost = Double.parseDouble(costPaidTxt.getText());
            java.util.Date adDate = adDateChooser.getDate();
            java.util.Date durationDate = (java.util.Date) adDurationSpinner.getValue();
            String status = (String) paymentStatusCombo.getSelectedItem();

            java.sql.Time sqlDuration = new java.sql.Time(durationDate.getTime());

            Advertisement ad = new Advertisement(
                adId,
                company,
                ch.getId(),
                pr.getProgramId(),
                cost,
                sqlDuration,
                new Date(adDate.getTime()),
                status
            );

            boolean success = adDao.updateAdvertisement(ad);
            if (success) {
                JOptionPane.showMessageDialog(this, "Advertisement updated successfully.");
                clearFields();
                loadAdvertisementTable();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Update failed. Check inputs.");
            e.printStackTrace();
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Select a row to delete.");
            return;
        }
        int adId = (int) jTable1.getValueAt(selectedRow, 0);
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this advertisement?");
        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = adDao.deleteAdvertisement(adId);
            if (success) {
                JOptionPane.showMessageDialog(this, "Advertisement deleted successfully.");
                clearFields();
                loadAdvertisementTable();
            }
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

