    private void setupDurationSpinner() {
    SpinnerDateModel timeModel = new SpinnerDateModel();
    adDurationSpinner.setModel(timeModel);

    JSpinner.DateEditor editor = new JSpinner.DateEditor(adDurationSpinner, "HH:mm");
    adDurationSpinner.setEditor(editor);

    // Default value = 00:00
    adDurationSpinner.setValue(new java.util.Date(0));
}

   // --- HELPER METHODS ---

    private void loadChannels() {
        channelNameCombo.removeAllItems();
        List<Channel> channels = channelDao.getAllChannels();
        for (Channel ch : channels) {
            channelNameCombo.addItem(ch);
        }
    }

    private void loadProgramsByChannel(int channelId) {
        programCombo.removeAllItems();
        List<Program> programs = programDao.getProgramsByChannel(channelId);
        for (Program p : programs) {
            programCombo.addItem(p);
        }
    }

    private void loadPaymentStatus() {
        paymentStatusCombo.removeAllItems();
        String[] statuses = {"Paid", "Pending", "Failed"};
        for (String s : statuses) {
            paymentStatusCombo.addItem(s);
        }
    }

    private void loadAdvertisementTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        List<Advertisement> ads = adDao.getAllAdvertisements();
        for (Advertisement ad : ads) {
            Channel ch = adDao.getChannelById(ad.getChannelId());
            Program pr = programDao.getProgramById(ad.getProgramId());

            Vector<Object> row = new Vector<>();
            row.add(ad.getAdId());
            row.add(ad.getCompanyName());
            row.add(ch != null ? ch.getName() : "");
            row.add(pr != null ? pr.getProgramName() : "");
            row.add(ad.getCostPaid());
            row.add(ad.getAdDuration());
            row.add(ad.getAdDate());
            row.add(ad.getPaymentStatus());

            model.addRow(row);
        }
    }

    private void clearFields() {
    companyNameTxt.setText("");
    costPaidTxt.setText("");
    adDurationSpinner.setValue(new java.util.Date(0)); // ✅ reset to 00:00
    adDateChooser.setDate(null);

    if (channelNameCombo.getItemCount() > 0) channelNameCombo.setSelectedIndex(0);
    if (programCombo.getItemCount() > 0) programCombo.setSelectedIndex(0);
    if (paymentStatusCombo.getItemCount() > 0) paymentStatusCombo.setSelectedIndex(0);
}


    
