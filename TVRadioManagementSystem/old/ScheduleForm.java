private void loadChannels() {
    List<Channel> channels = channelDao.getAllChannels();
    channelCombo.removeAllItems();
    for (Channel c : channels) {
        channelCombo.addItem(c); // Channel.toString() should return the channel name
    }
}

private void loadPrograms() {
    List<Program> programs = programDao.getAllPrograms();
    programCombo.removeAllItems();
    for (Program p : programs) {
        programCombo.addItem(p); // Program.toString() should return program name
    }
}

private void loadEmployees() {
    try {
        employeeCombo.removeAllItems();
        List<Employee> employees = employeeDao.getAllEmployeesWithNames();
        for (Employee e : employees) {
            employeeCombo.addItem(e); // will display firstName + lastName because of toString()
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Failed to load employees: " + ex.getMessage());
    }
}


// 4️⃣ Load Table
private void loadTable() {
    try {
        List<Schedule> list = scheduleDao.getAllSchedules();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (Schedule s : list) {
            Channel c = channelDao.getChannelById(s.getChannelId());
            Program p = programDao.getProgramById(s.getProgramId());
            Employee e = employeeDao.getEmployeeById(s.getEmployeeId());

            model.addRow(new Object[]{c.getName(), p.getName(), e.getFirstName()+" "+e.getLastName(),
                                     s.getStartTime(), s.getEndTime()});
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Table load error: "+e.getMessage());
    }
}
