    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
     
                                     
    try {
        Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
        Program selectedProgram = (Program) programCombo.getSelectedItem();
        Employee selectedEmployee = (Employee) employeeCombo.getSelectedItem();

        if (selectedChannel == null || selectedProgram == null || selectedEmployee == null) {
            JOptionPane.showMessageDialog(this, "Please select channel, program, and employee.");
            return;
        }

        Date start = (Date) startTimeSpinner.getValue();
        Date end = (Date) endTimeSpinner.getValue();

        if (end.before(start)) {
            JOptionPane.showMessageDialog(this, "End time must be after start time.");
            return;
        }

        Schedule schedule = new Schedule(0, selectedChannel.getId(), selectedProgram.getId(), 
                                         selectedEmployee.getId(), start, end);

        if (scheduleDao.addSchedule(schedule)) {
            JOptionPane.showMessageDialog(this, "Schedule added successfully!");
            loadTable();  // Refresh JTable
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add schedule.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
                                                 
    try {
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Select a schedule to update.");
            return;
        }

        int scheduleId = (int) jTable1.getValueAt(row, 0); // assuming first column stores ID
        Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
        Program selectedProgram = (Program) programCombo.getSelectedItem();
        Employee selectedEmployee = (Employee) employeeCombo.getSelectedItem();

        Date start = (Date) startTimeSpinner.getValue();
        Date end = (Date) endTimeSpinner.getValue();

        Schedule schedule = new Schedule(scheduleId, selectedChannel.getId(), selectedProgram.getId(),
                                         selectedEmployee.getId(), start, end);

        if (scheduleDao.updateSchedule(schedule)) {
            JOptionPane.showMessageDialog(this, "Schedule updated!");
            loadTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update schedule.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
                                                 
    try {
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Select a schedule to delete.");
            return;
        }

        int scheduleId = (int) jTable1.getValueAt(row, 0); // assuming first column stores ID

        if (scheduleDao.deleteSchedule(scheduleId)) {
            JOptionPane.showMessageDialog(this, "Schedule deleted!");
            loadTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to delete schedule.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_deleteBtnActionPerformed

