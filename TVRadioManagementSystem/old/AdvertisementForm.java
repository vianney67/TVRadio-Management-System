    private void loadChannelCombo() {
    try {
        ChannelDao dao = new ChannelDao();
        List<Channel> list = dao.getAllChannels();

        channelCombo.removeAllItems();
        for (Channel c : list) {
            channelCombo.addItem(c.getName());
        }

    } catch (Exception ex) {
        ex.printStackTrace();
    }
}

    private void loadTable() {
    try {
        AdvertisementDao dao = new AdvertisementDao();
        List<Advertisement> list = dao.getAllAdvertisements();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (Advertisement ad : list) {
            model.addRow(new Object[]{
                ad.getId(),
                ad.getTitle(),
                ad.getClientName(),
                ad.getFee(),
                ad.getStartTime(),
                ad.getEndTime(),
                ad.getChannelId()
            });
        }

    } catch (Exception ex) {
        ex.printStackTrace();
    }
}

    private void clearFields() {
    titleTxt.setText("");
    clientTxt.setText("");
    priceTxt.setText("");
    startDateChooser.setDate(null);
    endDateChooser.setDate(null);
    channelCombo.setSelectedIndex(-1);
}

    private void loadSelectedRow() {
    int row = jTable1.getSelectedRow();
    if (row == -1) return;

    titleTxt.setText(jTable1.getValueAt(row, 1).toString());
    clientTxt.setText(jTable1.getValueAt(row, 2).toString());
    priceTxt.setText(jTable1.getValueAt(row, 3).toString());

    startDateChooser.setDate((java.util.Date) jTable1.getValueAt(row, 4));
    endDateChooser.setDate((java.util.Date) jTable1.getValueAt(row, 5));

    channelCombo.setSelectedItem(jTable1.getValueAt(row, 6).toString());
}

    
