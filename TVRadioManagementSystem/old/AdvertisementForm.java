    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
                                              

    try {
        String title = titleTxt.getText();
        String client = clientTxt.getText();
        double price = Double.parseDouble(priceTxt.getText());
        java.util.Date start = startDateChooser.getDate();
        java.util.Date end = endDateChooser.getDate();
        String channelName = channelCombo.getSelectedItem().toString();

        ChannelDao cdao = new ChannelDao();
        Channel channel = cdao.getChannelByName(channelName);

        Advertisement ad = new Advertisement();
        ad.setTitle(title);
        ad.setClientName(client);
        ad.setFee(price);
        ad.setStartTime(start);
        ad.setEndTime(end);
        ad.setChannelId(channel.getId());


        AdvertisementDao dao = new AdvertisementDao();
        dao.addAdvertisement(ad);

        JOptionPane.showMessageDialog(this, "Advertisement added!");

        loadTable();
        clearFields();

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
                                                                                                                                                                  
    try {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select advertisement to update");
            return;
        }

        int id = (int) jTable1.getValueAt(row, 0);
        String title = titleTxt.getText().trim();
        String client = clientTxt.getText().trim();
        String feeStr = priceTxt.getText().trim();  // fee field
        java.util.Date start = startDateChooser.getDate();
        java.util.Date end = endDateChooser.getDate();
        String channelName = channelCombo.getSelectedItem().toString();

        if (title.isEmpty() || client.isEmpty() || feeStr.isEmpty() || start == null || end == null) {
            JOptionPane.showMessageDialog(this, "Please fill all fields");
            return;
        }

        // parse fee as double
        double fee;
        try {
            fee = Double.parseDouble(feeStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Fee must be a valid number");
            return;
        }

        // get channel id
        ChannelDao cdao = new ChannelDao();
        Channel channel = cdao.getChannelByName(channelName);
        if (channel == null) {
            JOptionPane.showMessageDialog(this, "Selected channel not found");
            return;
        }

        // create Advertisement object
        Advertisement ad = new Advertisement(id, title, client, channel.getId(), start, end, fee);

        // update in DB
        AdvertisementDao dao = new AdvertisementDao();
        boolean success = dao.updateAdvertisement(ad);

        if (success) {
            JOptionPane.showMessageDialog(this, "Advertisement updated!");
            loadTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update advertisement");
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        ex.printStackTrace();
    }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
                                                 
  
    try {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select advertisement to delete");
            return;
        }

        int id = (int) jTable1.getValueAt(row, 0);

        AdvertisementDao dao = new AdvertisementDao();
        dao.deleteAdvertisement(id);

        JOptionPane.showMessageDialog(this, "Advertisement deleted!");

        loadTable();
        clearFields();

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
    }
    }//GEN-LAST:event_deleteBtnActionPerformed

