    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
   
        try {
            String name = programNameTxt.getText();
            String type = typeCombo.getSelectedItem().toString();
            int duration = Integer.parseInt(durationTxt.getText());
            Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
            if (selectedChannel == null) {
                JOptionPane.showMessageDialog(this, "Select a channel");
                return;
            }

            Program program = new Program(0, name, type, duration, selectedChannel.getId());
            programDao.addProgram(program);
            loadTable();
            JOptionPane.showMessageDialog(this, "Program added successfully!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
       
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a program to update");
            return;
        }

        int programId = (int) jTable1.getValueAt(selectedRow, 0);
        String name = programNameTxt.getText();
        String type = typeCombo.getSelectedItem().toString();
        int duration;
        try {
            duration = Integer.parseInt(durationTxt.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Duration must be a number");
            return;
        }

        Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
        if (selectedChannel == null) {
            JOptionPane.showMessageDialog(this, "Select a channel");
            return;
        }

        Program program = new Program();
        program.setId(programId);
        program.setName(name);
        program.setType(type);
        program.setDuration(duration);
        program.setChannelId(selectedChannel.getId());

        if (programDao.updateProgram(program)) {
            JOptionPane.showMessageDialog(this, "Program updated successfully");
            try {
                loadTable();
            } catch (SQLException ex) {
                Logger.getLogger(ProgramForm.class.getName()).log(Level.SEVERE, null, ex);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update program");
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
                                          
    int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Select a program to delete");
        return;
    }

    int programId = (int) jTable1.getValueAt(selectedRow, 0);
    if (programDao.deleteProgram(programId)) {
        JOptionPane.showMessageDialog(this, "Program deleted successfully");
        try {
            loadTable(); // wrap in try-catch
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading table: " + e.getMessage());
        }
    } else {
        JOptionPane.showMessageDialog(this, "Failed to delete program");
    }
    }//GEN-LAST:event_deleteBtnActionPerformed

    private void retrievBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_retrievBtnActionPerformed

        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a program to retrieve");
            return;
        }

        programNameTxt.setText(jTable1.getValueAt(selectedRow, 1).toString());
        typeCombo.setSelectedItem(jTable1.getValueAt(selectedRow, 2).toString());
        durationTxt.setText(jTable1.getValueAt(selectedRow, 3).toString());

        String channelName = jTable1.getValueAt(selectedRow, 4).toString();
        for (int i = 0; i < channelCombo.getItemCount(); i++) {
            Channel ch = (Channel) channelCombo.getItemAt(i);
            if (ch.getName().equals(channelName)) {
                channelCombo.setSelectedIndex(i);
                break;
            }
        }
    
    }//GEN-LAST:event_retrievBtnActionPerformed

