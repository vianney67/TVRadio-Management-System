private void initializeDaos() throws SQLException {
    programDao = new ProgramDao();
    channelDao = new ChannelDao();
    loadChannels();
    loadTable();
}

// Load channels into combo box
private void loadChannels() throws SQLException {
    List<Channel> channels = channelDao.getAllChannels();
    channelCombo.removeAllItems();
    for (Channel c : channels) {
        channelCombo.addItem(c);
    }
}

// Load programs into table
private void loadTable() throws SQLException {
    List<Program> programs = programDao.getAllPrograms();
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    for (Program p : programs) {
        model.addRow(new Object[]{
            p.getId(),
            p.getName(),
            p.getType(),
            p.getDuration(),
            p.getChannelName()
        });
    }
}


