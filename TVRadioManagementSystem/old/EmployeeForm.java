    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
                                         
    try {
        String firstName = firstNameTxt.getText();
        String last = lastName.getText();
        String email = emailTxt.getText();
        String phone = phoneTxt.getText();
        String role = (String) roleCombo.getSelectedItem();
        Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
        Program selectedProgram = (Program) programCombo.getSelectedItem();
        String username = usernameTxt.getText();
        String password = new String(passwordTxt.getPassword());

        // Make sure a channel and program are selected
        if (selectedChannel == null || selectedProgram == null) {
            JOptionPane.showMessageDialog(this, "Please select a channel and a program.");
            return;
        }

        // Create employee with IDs only
        Employee emp = new Employee(
            0, 
            firstName, 
            last, 
            email, 
            phone, 
            role, 
            selectedChannel.getId(), 
            selectedProgram.getId(), 
            username, 
            password
        );

        // Add employee
        if (employeeDao.addEmployee(emp)) {
            JOptionPane.showMessageDialog(this, "Employee added successfully.");
            loadTable();   // reload JTable
            clearFields(); // clear form fields
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add employee.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error adding employee: " + e.getMessage());
    }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
      
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0) {
            try {
                int id = (int) jTable1.getValueAt(selectedRow, 0);
                String firstName = firstNameTxt.getText();
                String last = lastName.getText();
                String email = emailTxt.getText();
                String phone = phoneTxt.getText();
                String role = (String) roleCombo.getSelectedItem();
                Channel selectedChannel = (Channel) channelCombo.getSelectedItem();
                Program selectedProgram = (Program) programCombo.getSelectedItem();
                String username = usernameTxt.getText();
                String password = new String(passwordTxt.getPassword());

                Employee emp = new Employee(
        id,
        firstName,
        last,
        email,
        phone,
        role,
        selectedChannel.getId(),
        selectedProgram.getId(),
        username,
        password
);


                if (employeeDao.updateEmployee(emp)) {
                    JOptionPane.showMessageDialog(this, "Employee updated successfully.");
                    loadTable();
                    clearFields();
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error updating employee: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Select an employee from table to update.");
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0) {
            int id = (int) jTable1.getValueAt(selectedRow, 0);
            if (employeeDao.deleteEmployee(id)) {
                JOptionPane.showMessageDialog(this, "Employee deleted successfully.");
                loadTable();
                clearFields();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Select an employee from table to delete.");
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

