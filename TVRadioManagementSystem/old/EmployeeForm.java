private void initializeDaosAndLoadCombos() {
    channelDao = new ChannelDao();
    programDao = new ProgramDao();
    employeeDao = new EmployeeDao();

    loadChannels();
    loadPrograms();
}
private void loadChannels() {
    List<Channel> channels = channelDao.getAllChannels();
    channelCombo.removeAllItems();
    for (Channel c : channels) {
        channelCombo.addItem(c);  // ComboBox stores objects
    }
}

private void loadPrograms() {
    List<Program> programs = programDao.getAllPrograms();
    programCombo.removeAllItems();
    for (Program p : programs) {
        programCombo.addItem(p);  // ComboBox stores objects
    }
}


  private void loadTable() {
    List<Employee> employees = employeeDao.getAllEmployeesWithNames();
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    for (Employee e : employees) {
        model.addRow(new Object[]{
            e.getId(),
            e.getFirstName(),
            e.getLastName(),
            e.getEmail(),
            e.getPhone(),
            e.getRole(),
            e.getChannelName() != null ? e.getChannelName() : "",
            e.getProgramName() != null ? e.getProgramName() : "",
            e.getUsername()
        });
    }
}


    
